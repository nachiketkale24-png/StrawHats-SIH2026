// Generate the invisible GeoTIFF worker from the website's exact renderer.
const esbuild = require('esbuild')
const fs = require('fs')
const path = require('path')
const root = path.resolve(__dirname, '../..')
async function generate() {
const result = await esbuild.build({
  stdin: { contents: `import {loadEventRaster} from './frontend/src/lib/floodRaster';
    import {clearDisplayCache} from './frontend/src/lib/displayCache';
    let latest=0; window.renderFlood = async (request) => { const id=++latest;
      window.floodApiBase=request.apiBase;
      try { if(request.refresh) clearDisplayCache();
        const image=await loadEventRaster(request.event,new AbortController().signal,request.minutes,request.source);
        if(id===latest) window.ReactNativeWebView.postMessage(JSON.stringify({id:request.id,image}));
      } catch(error) { if(id===latest) window.ReactNativeWebView.postMessage(JSON.stringify({id:request.id,error:String(error.message||error)})); }
    }; window.ReactNativeWebView.postMessage(JSON.stringify({ready:true}));`, resolveDir: root },
  bundle: true, write: false, format: 'iife', minify: true,
  plugins: [{ name: 'native-api', setup(build) { build.onResolve({ filter: /^\.\/floodApi$/ }, () => ({ path: path.join(root, 'mobile/scripts/raster-api.js') })) } }],
})
const html = '<!doctype html><html><body><script>' + result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script') + '</script></body></html>'
fs.writeFileSync(path.join(root, 'mobile/src/components/rasterDecoder.ts'), '// Generated by scripts/build-raster-decoder.cjs; uses the shared website renderer.\nexport const rasterDecoderHtml = ' + JSON.stringify(html) + '\n')
}
generate().catch(error => { console.error(error); process.exitCode = 1 })
